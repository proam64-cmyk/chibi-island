// Measures the playing-field surface of the stadium GLB and writes src/config/stadiumFloor.ts
// (a 2 m height grid relative to the model base). Run again whenever env_stadium_*.glb changes:
//   node tools/build_stadium_floor.mjs assets/environment/env_stadium_v001.glb
import { readFileSync, writeFileSync } from 'node:fs';
import { Mesh, Vector3 } from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { MeshoptDecoder } from 'three/examples/jsm/libs/meshopt_decoder.module.js';

const file = process.argv[2] ?? 'assets/environment/env_stadium_v001.glb';
const buf = readFileSync(file);
// Drop images so the GLB parses in Node.
const jl = buf.readUInt32LE(12); const json = JSON.parse(buf.subarray(20, 20 + jl).toString());
delete json.images; delete json.textures; delete json.samplers;
for (const m of json.materials ?? []) { delete m.normalTexture; if (m.pbrMetallicRoughness) delete m.pbrMetallicRoughness.baseColorTexture; }
if (json.extensionsRequired) json.extensionsRequired = json.extensionsRequired.filter((e) => e !== 'EXT_texture_webp');
const js = Buffer.from(JSON.stringify(json)); const jsonChunk = Buffer.concat([js, Buffer.alloc((4 - (js.length % 4)) % 4, 0x20)]);
const binStart = 20 + jl, binLen = buf.readUInt32LE(binStart), bin = buf.subarray(binStart + 8, binStart + 8 + binLen);
const out = Buffer.alloc(28 + jsonChunk.length + bin.length);
out.writeUInt32LE(0x46546c67, 0); out.writeUInt32LE(2, 4); out.writeUInt32LE(out.length, 8);
out.writeUInt32LE(jsonChunk.length, 12); out.writeUInt32LE(0x4e4f534a, 16); jsonChunk.copy(out, 20);
const b = 20 + jsonChunk.length; out.writeUInt32LE(bin.length, b); out.writeUInt32LE(0x004e4942, b + 4); bin.copy(out, b + 8);

const gltf = await new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).parseAsync(out.buffer.slice(out.byteOffset, out.byteOffset + out.length), '');
gltf.scene.updateMatrixWorld(true);
const RADIUS = 38, CELL = 2, N = Math.round((2 * RADIUS) / CELL) + 1;
const top = new Float32Array(N * N).fill(-Infinity);
const v = new Vector3();
gltf.scene.traverse((o) => {
  if (!(o instanceof Mesh)) return;
  const pos = o.geometry.attributes.position;
  const idx = o.geometry.index;
  // Rasterize triangle centroids + vertices (dense enough at 2 m cells for a ~66 k triangle mesh).
  const tri = idx ? idx.count / 3 : pos.count / 3;
  const a = new Vector3(), c = new Vector3(), d = new Vector3();
  for (let t = 0; t < tri; t++) {
    const i0 = idx ? idx.getX(t * 3) : t * 3, i1 = idx ? idx.getX(t * 3 + 1) : t * 3 + 1, i2 = idx ? idx.getX(t * 3 + 2) : t * 3 + 2;
    a.fromBufferAttribute(pos, i0).applyMatrix4(o.matrixWorld); c.fromBufferAttribute(pos, i1).applyMatrix4(o.matrixWorld); d.fromBufferAttribute(pos, i2).applyMatrix4(o.matrixWorld);
    for (const [wa, wc, wd] of [[1, 0, 0], [0, 1, 0], [0, 0, 1], [1 / 3, 1 / 3, 1 / 3], [0.5, 0.5, 0], [0, 0.5, 0.5], [0.5, 0, 0.5]]) {
      v.set(a.x * wa + c.x * wc + d.x * wd, a.y * wa + c.y * wc + d.y * wd, a.z * wa + c.z * wc + d.z * wd);
      const i = Math.round((v.x + RADIUS) / CELL), j = Math.round((v.z + RADIUS) / CELL);
      if (i < 0 || j < 0 || i >= N || j >= N) continue;
      if (v.y < 20 && v.y > top[j * N + i]) top[j * N + i] = v.y; // ignore anything far above the field (none inside the bowl)
    }
  }
});
// Fill empty cells from neighbours, then write centimetres.
for (let pass = 0; pass < 6; pass++) for (let j = 0; j < N; j++) for (let i = 0; i < N; i++) {
  if (top[j * N + i] !== -Infinity) continue;
  let s = 0, n = 0;
  for (const [di, dj] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) { const ii = i + di, jj = j + dj; if (ii >= 0 && jj >= 0 && ii < N && jj < N && top[jj * N + ii] !== -Infinity) { s += top[jj * N + ii]; n++; } }
  if (n) top[j * N + i] = s / n;
}
// Cells that only caught the model base (gaps between big field triangles) take their neighbourhood median.
const fixed = Float32Array.from(top);
for (let j = 0; j < N; j++) for (let i = 0; i < N; i++) {
  const around = [];
  for (let dj = -2; dj <= 2; dj++) for (let di = -2; di <= 2; di++) { const ii = i + di, jj = j + dj; if (ii >= 0 && jj >= 0 && ii < N && jj < N && Number.isFinite(top[jj * N + ii])) around.push(top[jj * N + ii]); }
  around.sort((x, y) => x - y);
  const med = around[around.length >> 1];
  if (med !== undefined && top[j * N + i] < med - 1.0) fixed[j * N + i] = med;
}
const cm = Array.from(fixed, (h) => (Number.isFinite(h) ? Math.round(h * 100) : 0));
writeFileSync('src/config/stadiumFloor.ts', `/** Generated by tools/build_stadium_floor.mjs from ${file.split('/').pop()} — do not edit by hand.
 * Top surface of the stadium field, in centimetres above the model base, on a ${CELL} m grid centred on the stadium. */
export const STADIUM_FLOOR = { radius: ${RADIUS}, cell: ${CELL}, size: ${N}, cm: [${cm.join(',')}] } as const;
`);
const inner = cm.filter((_, k) => Math.hypot((k % N) * CELL - RADIUS, Math.floor(k / N) * CELL - RADIUS) < 30);
console.log('cells', N * N, 'field height (inner 30 m): min', Math.min(...inner) / 100, 'max', Math.max(...inner) / 100, 'median', inner.sort((x, y) => x - y)[inner.length >> 1] / 100);
