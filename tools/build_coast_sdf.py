"""Builds src/world/island/coastSdfData.ts from the official map image.
Usage: python3 tools/build_coast_sdf.py path/to/Chibi_Island__Crystal_Shores_Map.png
Requires numpy, pillow, scipy, matplotlib. Steps: classify sea by hue/saturation, remove UI overlays
(title, legend, compass) and clouds, keep land blobs > 400 px, downsample 4× (6.25 m cells),
signed distance transform, quantize to 1 m (uint8, +128 offset), base64 into a TS module."""
import sys, base64
import numpy as np
from PIL import Image
import matplotlib.colors as mc
from scipy import ndimage

im = Image.open(sys.argv[1]).convert('RGB')
a = np.array(im).astype(float) / 255
hsv = mc.rgb_to_hsv(a); h, s, v = hsv[..., 0], hsv[..., 1], hsv[..., 2]
H, W = h.shape; Y = np.arange(H)[:, None]; X = np.arange(W)[None, :]
water = (h > 0.47) & (h < 0.68) & (s > 0.35)
mountain = (X > 560) & (X < 1060) & (Y < 330)
water &= ~(mountain & (s < 0.75))
cloud = (s < 0.12) & (v > 0.85)
water[int(H*0.74):, int(W*0.83):] = True; water[:int(H*0.17), :int(W*0.29)] = True; water[int(H*0.8):, :int(W*0.16)] = True
water[:int(H*0.14), int(W*0.67):] = True
water |= cloud & (Y < H*0.2) & ((X < W*0.36) | (X > W*0.69))
land = ndimage.binary_fill_holes(ndimage.binary_closing(ndimage.binary_opening(~water, iterations=3), iterations=6))
lab, n = ndimage.label(land); sizes = ndimage.sum(land, lab, range(1, n + 1))
keep = np.isin(lab, 1 + np.where(sizes > 400)[0])
MPP, f = 1.5625, 4; Hs, Ws = H // f, W // f; cell = MPP * f
small = keep[:Hs*f, :Ws*f].reshape(Hs, f, Ws, f).mean((1, 3)) > 0.5
sdf = np.where(small, ndimage.distance_transform_edt(small)*cell - cell/2, -(ndimage.distance_transform_edt(~small)*cell - cell/2))
q = np.clip(np.round(sdf + 128), 0, 255).astype(np.uint8)
enc = base64.b64encode(q.tobytes()).decode()
open('src/world/island/coastSdfData.ts', 'w').write(
  "/** Generated by tools/build_coast_sdf.py — do not edit by hand. Signed distance to the coast (m), + land / − sea. */\n"
  f"export const COAST_GRID = {{ cols: {Ws}, rows: {Hs}, cell: {cell}, originX: {-860*MPP}, originZ: {-500*MPP} }} as const;\n"
  f"export const COAST_SDF_B64 = '{enc}';\n")
print('ok', Ws, Hs)
