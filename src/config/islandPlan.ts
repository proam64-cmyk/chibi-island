/**
 * Official island plan — based on the user's map "Chibi Island: Crystal Shores" (approved 2026-10-24),
 * scaled to ≈ 2.4 × 1.6 km. 1 unit = 1 m, origin = Chibi Town plaza, north = −Z, east = +X, sea level = 0.
 * Map zones → game districts: Chibi Town = Plaza + Lantern Street + Izakaya; Harbor Bay = harbor + residential;
 * Sunset Beach = beach; Crystal Peak = Winter Atelier; plus Sky Terrace, Lumi Forest, Volcano Cliffs and the stadium.
 */
export interface DistrictDef {
  id: string;
  /** i18n key for the name */
  nameKey: string;
  x: number;
  z: number;
  /** radius of the zone (m) */
  radius: number;
  /** target ground height of the buildable plateau (m) */
  elevation: number;
  /** 0 = keep natural terrain (forest, volcano) … 1 = fully flat plateau */
  flatten: number;
  color: string;
  /** Where fast travel (keys 1–0) puts the player, if not the zone center (e.g. not inside the crater). */
  spawn?: [number, number];
}

